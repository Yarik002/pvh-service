#!/bin/sh
# =====================================================================
#  Сценарий запуска контейнера.
#
#  Каталог data подключается как том, поэтому права на него зависят
#  от того, кто создал файлы: при первом запуске контейнера они могут
#  принадлежать суперпользователю. Тогда SQLite не сможет записать
#  данные и вернёт ошибку «attempt to write a readonly database».
#
#  Сценарий выполняется от суперпользователя, выравнивает права
#  на каталог данных и запускает приложение от непривилегированной
#  учётной записи node.
#
#  Для смены пользователя применяется setpriv из состава util-linux:
#  он входит в базовый образ и не требует установки дополнительных пакетов.
# =====================================================================

set -e

APP_USER="${APP_USER:-node}"
APP_UID="${APP_UID:-1000}"
APP_GID="${APP_GID:-1000}"

DATA_DIR="$(dirname "${DB_FILE:-/app/data/pvh.db}")"

echo "Подготовка каталога данных: ${DATA_DIR}"
mkdir -p "${DATA_DIR}"

# Права выравниваются только при необходимости: на смонтированном томе
# команда chown может завершиться ошибкой, и это не должно прерывать запуск
if [ "$(id -u)" = "0" ]; then
  chown -R "${APP_UID}:${APP_GID}" "${DATA_DIR}" 2>/dev/null || \
    echo "Предупреждение: не удалось изменить владельца ${DATA_DIR}"
fi

# Команда запуска приложения от имени пользователя node
run_as_app() {
  if [ "$(id -u)" = "0" ]; then
    exec setpriv --reuid="${APP_UID}" --regid="${APP_GID}" --init-groups "$@"
  fi
  exec "$@"
}

if [ "$#" -gt 0 ]; then
  # Контейнер запущен с явно указанной командой: выполняем её
  echo "Выполнение команды: $*"
  run_as_app "$@"
fi

echo "Применение миграций…"
setpriv --reuid="${APP_UID}" --regid="${APP_GID}" --init-groups node scripts/migrate.js

echo "Создание учётной записи администратора и справочника ячеек…"
setpriv --reuid="${APP_UID}" --regid="${APP_GID}" --init-groups node scripts/seed.js

echo "Запуск сервера…"
exec setpriv --reuid="${APP_UID}" --regid="${APP_GID}" --init-groups node src/server.js

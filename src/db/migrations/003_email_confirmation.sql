-- =====================================================================
--  Миграция 003. Подтверждение адреса электронной почты.
--
--  Добавляются поля:
--    confirm_token_created_at — дата и время формирования текущего токена
--                               подтверждения (нужна для проверки срока действия
--                               ссылки из письма);
--    confirm_attempts         — число неудачных попыток подтверждения
--                               (защита токена от подбора).
--
--  После успешного подтверждения значение confirm_token очищается, поэтому
--  ссылка из письма становится недействительной: повторное использование
--  одного и того же токена невозможно.
-- =====================================================================

ALTER TABLE Users ADD COLUMN confirm_token_created_at TEXT;

ALTER TABLE Users ADD COLUMN confirm_attempts INTEGER NOT NULL DEFAULT 0
    CHECK (confirm_attempts >= 0);

-- Частичный индекс для поиска по действующим токенам подтверждения
CREATE INDEX IF NOT EXISTS idx_users_confirm_token
    ON Users (confirm_token)
    WHERE confirm_token IS NOT NULL;
